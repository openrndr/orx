#!/usr/bin/env python3
"""
Generates orx-color's PigmentReflectances.kt from the CHSOS Pigments Checker FORS spectra.

Usage:
    python3 tools/generate_pigment_reflectances.py <folder with the CHSOS .txt files>

Every input file has two columns: wavelength in nm and reflectance in percent, sampled at about 0.17 nm. The
spectra are reduced to the grid of org.openrndr.extra.color.mixing (38 samples from 380 to 750 nm in steps of
10 nm) by averaging all measurements within +/- 5 nm of each sample wavelength, which also averages out noise.
"""
import glob
import os
import re
import sys

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "commonMain", "kotlin", "mixing", "PigmentReflectances.kt")
WAVELENGTHS = list(range(380, 751, 10))
HALF_WIDTH = 5.0

# abbreviations and typos in the file names, expanded for the Kotlin property names
WORDS = {"y": "yellow", "b": "blue", "art": "artificial", "nat": "natural", "die": "dye", "methilene": "methylene",
         "alizarine": "alizarin", "still": "stil"}


def read_spectrum(path):
    points = []
    with open(path, encoding="latin-1") as f:
        for line in f:
            parts = line.replace(",", ".").split()
            if len(parts) >= 2:
                points.append((float(parts[0]), float(parts[1])))
    return points


def resample(points):
    samples = []
    for wavelength in WAVELENGTHS:
        band = [r for w, r in points if abs(w - wavelength) <= HALF_WIDTH]
        if not band:
            raise SystemExit(f"no data around {wavelength} nm")
        samples.append(sum(band) / len(band) / 100.0)
    return samples


def identifier(name):
    # "PY 3 - hansa yellow 10G" -> color index "PY 3", name "hansa yellow 10G"
    m = re.match(r"^([A-Z][A-Za-z]* ?\d+) - (.*)$", name)
    color_index, label = (m.group(1), m.group(2)) if m else (None, name)
    words = [WORDS.get(w.lower(), w) for w in re.split(r"[\s-]+", label) if w]
    camel = words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:])
    return re.sub(r"[^A-Za-z0-9]", "", camel), color_index


def kotlin_array(values):
    text = ", ".join(f"{v:.4f}" for v in values)
    rows, row = [], ""
    for item in text.split(", "):
        if len(row) + len(item) + 2 > 108:
            rows.append(row.rstrip())
            row = ""
        row += item + ", "
    rows.append(row.rstrip().rstrip(","))
    return "\n".join("        " + r for r in rows)


def main(folder):
    files = glob.glob(os.path.join(folder, "*.txt"))
    entries = []
    for path in files:
        name = os.path.basename(path)[:-len(".txt")]
        ident, color_index = identifier(name)
        entries.append((name, ident, color_index, resample(read_spectrum(path))))
    entries.sort(key=lambda e: e[1].lower())
    if len({e[1] for e in entries}) != len(entries):
        raise SystemExit("duplicate identifiers")

    out = ["// Generated by tools/generate_pigment_reflectances.py from the CHSOS Pigments Checker FORS spectra, do not edit.",
           "",
           "package org.openrndr.extra.color.mixing",
           "",
           "/**",
           " * Measured reflectance spectra of historical and modern pigments, for use with [mixReflectance] and",
           " * [reflectanceToRGBa].",
           " *",
           " * Every spectrum has 38 samples from 380 to 750 nm in steps of 10 nm, the grid used by [linearToReflectance] and",
           " * [reflectanceToXYZ]. The spectra were measured with fiber optics reflectance spectroscopy (FORS) by Cultural",
           " * Heritage Science Open Source (CHSOS, https://chsopensource.org) on the swatches of their Pigments Checker, see",
           " * A. Cosentino, *FORS spectral database of historical pigments in different binders*, e-conservation Journal 2,",
           " * 57-68 (2014). Each sample is the average of all measurements within 5 nm of its wavelength.",
           " *",
           " * The swatches are pigment samples in a binder for pigment identification, not opaque paint layers, so mixing",
           " * them with Kubelka-Munk theory is an approximation, in particular for transparent pigments such as lakes.",
           " * Every property returns a new copy of the spectrum.",
           " */",
           "object PigmentReflectances {"]
    for name, ident, color_index, values in entries:
        const = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", ident).upper()
        out.append(f"    private val {const} = doubleArrayOf(\n{kotlin_array(values)}\n    )")
    out.append("")
    for name, ident, color_index, values in entries:
        const = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", ident).upper()
        note = f" ({color_index})" if color_index else ""
        out.append(f"    /** CHSOS spectrum \"{name}\"{note} */\n    val {ident}: DoubleArray get() = {const}.copyOf()\n")
    out.append("    /**\n     * All spectra by their CHSOS name.\n     */")
    out.append("    val all: Map<String, DoubleArray>\n        get() = linkedMapOf(\n" +
               ",\n".join(f'            "{name}" to {ident}' for name, ident, _, _ in entries) + "\n        )\n}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"generated {len(entries)} spectra: " + ", ".join(e[1] for e in entries))


if __name__ == "__main__":
    main(sys.argv[1])
